import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const {initial,transition}=createRequire(import.meta.url)('../../frontend/src/shared/app-state.js');
let state=initial({hasLocalStory:true});
assert.equal(state.story.status,'saved');
assert.equal(state.authentication.status,'signedOut','A local profile is not a verified session');
const original=state,originalAuth=state.authentication;
state=transition(state,{type:'OPEN_DIALOG',dialog:'profile'});
assert.equal(state.navigation.dialog,'profile');assert.equal(state.story.status,'editing');
assert.equal(state.authentication,originalAuth);assert.equal(original.story.status,'saved');
assert.throws(()=>{state.story.status='saved';},TypeError);
assert.equal(transition(state,{type:'NAVIGATE',view:'dashboard'}),state,'An open modal prevents background navigation');
state=transition(state,{type:'SAVE_STARTED'});assert.equal(state.story.status,'saving');
assert.equal(transition(state,{type:'SAVE_STARTED'}),state,'Repeated save start is ignored');
state=transition(state,{type:'SAVE_FAILED',error:'Connection lost'});assert.equal(state.story.status,'saveFailed');assert.equal(state.navigation.dialog,'profile');
state=transition(state,{type:'SAVE_STARTED'});
state=transition(state,{type:'SAVE_SUCCEEDED',id:'mine',persistence:'sessionOnly'});
assert.equal(state.story.persistence,'sessionOnly');assert.equal(state.navigation.dialog,null);
state=transition(state,{type:'OPEN_DIALOG',dialog:'info'});
assert.equal(transition(state,{type:'CLOSE_DIALOG',dialog:'profile'}),state,'Delayed editor close cannot close a different dialog');
state=transition(state,{type:'CLOSE_DIALOG',dialog:'info'});
state=transition(state,{type:'NAVIGATE',view:'dashboard'});assert.equal(state.navigation.view,'dashboard');assert.equal(state.story.status,'saved');
state=transition(state,{type:'AUTH_CHANGED',status:'checking'});
state=transition(state,{type:'AUTH_CHANGED',status:'checkFailed',error:'Offline'});assert.equal(state.authentication.status,'checkFailed');assert.equal(state.story.status,'saved');
state=transition(state,{type:'AUTH_CHANGED',status:'checking'});
assert.throws(()=>transition(state,{type:'AUTH_CHANGED',status:'signedIn'}),TypeError);
state=transition(state,{type:'AUTH_CHANGED',status:'signedIn',user:{id:'user-1',nickname:'Nam',accessToken:'must-not-be-stored'}});
assert.deepEqual(Object.keys(state.authentication.user),['id','nickname']);
state=transition(state,{type:'AUTH_CHANGED',status:'signingOut'});
state=transition(state,{type:'AUTH_CHANGED',status:'signedIn'});assert.equal(state.authentication.user.id,'user-1');
state=transition(state,{type:'AUTH_CHANGED',status:'signedOut'});assert.equal(state.authentication.user,null);assert.equal(state.story.id,'mine','Signing out is distinct from deleting a story');
state=transition(state,{type:'LOCAL_STORY_CLEARED'});assert.equal(state.story.status,'none');
state=transition(state,{type:'OPEN_DIALOG',dialog:'profile'});
state=transition(state,{type:'CLOSE_DIALOG',dialog:'profile'});assert.equal(state.story.status,'none');
assert.throws(()=>transition(state,{type:'NAVIGATE',view:'unknown'}),RangeError);
assert.throws(()=>transition(state,{type:'OPEN_DIALOG',dialog:'unknown'}),RangeError);
assert.throws(()=>transition(state,{type:'AUTH_CHANGED',status:'unknown'}),RangeError);
assert.throws(()=>transition(state,{type:'UNKNOWN'}),RangeError);
assert.equal(transition(initial(),{type:'SAVE_SUCCEEDED',id:'unexpected',persistence:'server'}).story.status,'none','Ignore stale async completion');
console.log('PASS: independent navigation/auth/story state, guarded transitions, immutable snapshots, save retry/session-only persistence, stale close/save events, local profile isolation and session identity validation.');
