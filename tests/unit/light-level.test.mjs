import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const context=vm.createContext({});
for(const file of ['frontend/src/community/map-layout.js','frontend/data/demo-data.js'])vm.runInContext(fs.readFileSync(new URL('../../'+file,import.meta.url),'utf8'),context);
const run=code=>vm.runInContext(code,context);
for(const [count,level] of [[0,0],[1,1],[10,1],[11,2],[50,2],[51,3],[55,3],[100,3],[101,4],[200,4],[201,5],[500,5],[501,6],[600,6]])assert.equal(run(`lightLevel(${count})`),level);
run(`const fixture=Array.from({length:100},(_,i)=>({id:'test-'+i,city:i<55?'Malmö':'Stockholm',status:'Found work',lit:true}));`);
assert.equal(run('kommunLights(fixture).get("Malmö").count'),55);
assert.equal(run('kommunLights(fixture).get("Malmö").level'),3);
assert.equal(run('kommunLights(fixture).get("Stockholm").level'),2);
assert.equal(run(`kommunLights(Array.from({length:600},()=>({city:'Stockholm',status:'Found work',lit:true}))).get('Stockholm').level`),6);
assert.equal(run(`kommunLights([{city:'Malmö',status:'Found work',lit:false},{city:'Malmö',status:'Looking for an opportunity',lit:true},{city:'Malmö',status:'Found work',lit:true,visible:false}]).get('Malmö').level`),0);
assert.equal(run(`kommunLights([{city:'Akalla',kommun:'Stockholm',status:'Found work',lit:true},{city:'Stockholm',kommun:'Stockholm',status:'Found work',lit:true}]).get('Stockholm').count`),2);
assert.equal(run('samples.length'),100);
assert.equal(run('[...kommunLights(samples).values()].reduce((n,g)=>n+g.count,0)'),run("samples.filter(p=>p.lit&&p.status==='Found work').length"));
console.log('PASS: all light boundaries, 100-user Malmö 55/Stockholm 45 fixture, Stockholm 600, eligibility, explicit kommun grouping, existing 100 demo profiles.');
