create table public.stories(
 id uuid primary key default gen_random_uuid(),
 owner_id uuid not null unique references auth.users(id) on delete cascade default auth.uid(),
 nickname text not null check(char_length(trim(nickname)) between 1 and 40),
 city text not null references public.story_cities(name),
 message text not null default '' check(char_length(message)<=600),
 status text not null default '' check(status in ('','Looking for an opportunity','Found work','Here to encourage')),
 seeking text not null default '' check(seeking in ('','Full-time','Part-time','Internship','Other')),
 role text not null default '' check(char_length(role)<=80),
 company text not null default '' check(char_length(company)<=80),
 lit boolean not null default true, visible boolean not null default true
);
alter table public.stories enable row level security;
create policy story_owner_read on public.stories for select to authenticated using(owner_id=(select auth.uid()));
create policy story_owner_insert on public.stories for insert to authenticated with check(owner_id=(select auth.uid()));
create policy story_owner_update on public.stories for update to authenticated using(owner_id=(select auth.uid())) with check(owner_id=(select auth.uid()));
create policy story_owner_delete on public.stories for delete to authenticated using(owner_id=(select auth.uid()));
revoke all on public.stories from public,anon,authenticated;
grant select,insert,update,delete on public.stories to authenticated;
-- Deliberately owner-executed, barrier-protected projection: no owner IDs or hidden rows.
create view public.public_stories with(security_barrier=true) as
 select id,nickname,city,message,status,seeking,role,company,lit,visible from public.stories where visible;
revoke all on public.public_stories from public;
grant select on public.public_stories to anon,authenticated;
commit;
